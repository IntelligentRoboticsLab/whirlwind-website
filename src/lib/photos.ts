const byId = new Map(photos.map((p) => [p.id, p]));

// A photo by its id. Throws at build time when the id is wrong, so a typo in a
// news map cannot ship a missing picture.
export function photo(id: string): Photo {
  const p = byId.get(id);
  if (!p) throw new Error(`Unknown photo: ${id}`);
  return p;
}

// The Press gallery: everything not opted out, newest event first.
